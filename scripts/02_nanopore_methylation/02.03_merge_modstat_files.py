"""Purpose: Filter and merge per-sample 5 kb methylation statistics.

Input: Per-sample TSV files generated by ``02.02_5kb_bin_modstat.sh``.
Output: Filtered per-sample TSV files and one merged TSV.GZ matrix.
"""

import gzip
import os


INPUT_DIR = "results/02_nanopore_methylation/2.2_modkit_stats"
OUTPUT_DIR = "results/02_nanopore_methylation/threshold_10"
FINAL_OUTPUT = "results/02_nanopore_methylation/threshold_10_discovery_cohort_methylationfile.tsv.gz"
THRESHOLD = 10


def main() -> None:
    input_files = sorted([f for f in os.listdir(INPUT_DIR) if f.endswith(".tsv") and f != FINAL_OUTPUT])

    for file in input_files:
        file_basename = file[:-4]
        in_path = os.path.join(INPUT_DIR, file)
        out_path = os.path.join(OUTPUT_DIR, f"{file_basename}_threshold{THRESHOLD}.tsv")
        with open(in_path, "r") as f_in, open(out_path, "w") as f_out:
            lines = f_in.readlines()
            header_line = lines[0].rstrip("\n")
            f_out.write(header_line + "\n")
            headers = header_line.split("\t")

            idx_valid = headers.index("count_valid_m")
            idx_percent = headers.index("percent_m")

            for line in lines[1:]:
                cols = line.rstrip("\n").split("\t")
                if len(cols) <= max(idx_valid, idx_percent):
                    continue
                try:
                    v = float(cols[idx_valid])
                    if v < THRESHOLD:
                        cols[idx_percent] = "NA"
                except ValueError:
                    pass
                f_out.write("\t".join(cols) + "\n")

    file_names = sorted([f for f in os.listdir(OUTPUT_DIR) if f.endswith(f"_threshold{THRESHOLD}.tsv")])
    per_file_maps = []
    all_positions = set()

    for fn in file_names:
        path = os.path.join(OUTPUT_DIR, fn)
        pos2val = {}
        with open(path, "r") as f:
            headers = f.readline().rstrip("\n").split("\t")
            idx_chrom = headers.index("chrom")
            idx_start = headers.index("start")
            idx_end = headers.index("end")
            idx_percent = headers.index("percent_m")

            for line in f:
                cols = line.rstrip("\n").split("\t")
                pos = (cols[idx_chrom], cols[idx_start], cols[idx_end])
                pos2val[pos] = cols[idx_percent]
                all_positions.add(pos)
        per_file_maps.append(pos2val)

    sample_names = [fn.replace(f"_threshold{THRESHOLD}.tsv", "") for fn in file_names]
    out_headers = ["chr", "start", "end"] + sample_names

    with gzip.open(FINAL_OUTPUT, "wt") as out:
        out.write("\t".join(out_headers) + "\n")
        for pos in sorted(all_positions):
            row = list(pos)
            for fmap in per_file_maps:
                row.append(fmap.get(pos, "NA"))
            out.write("\t".join(row) + "\n")


if __name__ == "__main__":
    main()
